export function resolveLocale(pref: 'auto' | Locale, system: string): Locale {
  if (pref !== 'auto') return pref;
  return system.toLowerCase().startsWith('zh') ? 'zh-CN' : 'en';
}

export function t(locale: Locale, key: string, params: Record<string, string | number> = {}): string {
  const dict = locale === 'zh-CN' ? zh : en;
  const template = dict[key] ?? en[key] ?? key;
  return template.replace(/\{(\w+)\}/g, (_, k: string) => (k in params ? String(params[k]) : `{${k}}`));
}

export function hasKey(key: string): boolean {
  return key in en;
}

export function bubbleLines(locale: Locale, mood: Mood): string[] {
  return bubbles[locale][mood];
}
